package Renderer;

public class Point {

    public float x;
    public float y;
    public float z;


    public Point(float x, float y, float z){
        this.x = x;
        this.y = y;
        this.z = z;
    }
    public Point(){
        this.x = 0;
        this.y = 0;
        this.z = 0;
    }

}
